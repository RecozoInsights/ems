"""
Employee Management System
Includes: Encapsulation, Inheritance/Polymorphism, Strategy, Factory,
State, Observer (OOP stages) + Day 2 DB changes (employee_id is now
assigned by the database, not an in-memory counter).
"""

from abc import ABC, abstractmethod
import itertools


# =========================================================
# Factory Pattern
# =========================================================
class EmployeeFactory:
    @staticmethod
    def create_employee(employee_type: str, name: str, base_salary: float, **kwargs):
        role_map = {
            "manager": Manager,
            "developer": Developer,
            "intern": Intern
        }
        if employee_type.lower() in role_map:
            return role_map[employee_type.lower()](name, base_salary, **kwargs)
        else:
            raise ValueError(f"Unknown employee type: {employee_type}")


# =========================================================
# Encapsulation, Inheritance & Polymorphism
# =========================================================
class Employee(ABC):
    # NOTE (Day 2 change): employee_id is no longer generated by an
    # in-memory itertools counter. The database now owns ID assignment
    # (AUTOINCREMENT), since the DB is durable across restarts and the
    # old in-memory counter would reset to 1 every time the app restarted,
    # colliding with IDs already stored on disk.
    def __init__(self, name: str, base_salary: float, hours_worked: int = 0,
                 hourly_rate: float = 0.0, payroll_strategy=None, employee_id=None):
        self.employee_id = employee_id  # None until Department.add_employee() inserts it
        self.name = name
        self.base_salary = base_salary
        self.hours_worked = hours_worked
        self.hourly_rate = hourly_rate
        self._leave_balance = 20
        self.payroll_strategy = payroll_strategy if payroll_strategy is not None else SalariedStrategy()

    @property
    def leave_balance(self):
        return self._leave_balance

    def deduct_leave(self, days: int):
        if days <= self._leave_balance:
            self._leave_balance -= days
        else:
            raise ValueError("Insufficient leave balance")

    def restore_leave(self, days: int):
        self._leave_balance += days

    def calculate_salary(self):
        return self.payroll_strategy.calculate(self)

    @property
    @abstractmethod
    def bonus_multiplier(self):
        pass

    def __repr__(self):
        return (f"{self.__class__.__name__}(ID: {self.employee_id}, Name: {self.name}, "
                f"Base Salary: {self.base_salary}, Leave Balance: {self._leave_balance})")


class Manager(Employee):
    @property
    def bonus_multiplier(self):
        return 1.2  # Managers get a 20% bonus


class Developer(Employee):
    @property
    def bonus_multiplier(self):
        return 1.1  # Developers get a 10% bonus


class Intern(Employee):
    @property
    def bonus_multiplier(self):
        return 1.0  # Interns do not get a bonus


# =========================================================
# Strategy Pattern (payroll calculation)
# =========================================================
class PayrollStrategy(ABC):
    @abstractmethod
    def calculate(self, employee):
        pass


class SalariedStrategy(PayrollStrategy):
    def calculate(self, employee):
        return employee.base_salary * employee.bonus_multiplier


class HourlyStrategy(PayrollStrategy):
    def calculate(self, employee):
        return employee.hours_worked * employee.hourly_rate


# =========================================================
# State Pattern (leave request lifecycle)
# =========================================================
class LeaveState(ABC):
    @abstractmethod
    def approve(self, leave_request):
        pass

    @abstractmethod
    def reject(self, leave_request):
        pass


class PendingState(LeaveState):
    def approve(self, leave_request):
        leave_request.employee.deduct_leave(leave_request.days)
        leave_request.state = ApprovedState()

    def reject(self, leave_request):
        leave_request.state = RejectedState()


class ApprovedState(LeaveState):
    def approve(self, leave_request):
        raise ValueError("Leave already approved.")

    def reject(self, leave_request):
        raise ValueError("Cannot reject an already approved leave.")


class RejectedState(LeaveState):
    def approve(self, leave_request):
        raise ValueError("Cannot approve a rejected leave.")

    def reject(self, leave_request):
        raise ValueError("Leave already rejected.")


# =========================================================
# Observer Pattern (notifications)
# =========================================================
class Observer(ABC):
    @abstractmethod
    def update(self, leave_request, event: str):
        pass


class EmailNotifier(Observer):
    def update(self, leave_request, event: str):
        print(f"Email sent to {leave_request.employee.name}: "
              f"your leave request was {event}.")


class AuditLogger(Observer):
    def __init__(self):
        self.logs = []

    def update(self, leave_request, event: str):
        message = (f"[AUDIT] LeaveRequest for {leave_request.employee.name}, "
                   f"{leave_request.days} days -> {event}")
        self.logs.append(message)
        print(message)


# =========================================================
# LeaveRequest (State subject + Observer subject)
# NOTE: still in-memory ID generation here -- this gets migrated to the
# database on Day 3 (its own table + foreign key to employees).
# =========================================================
class LeaveRequest:
    def __init__(self, employee: Employee, days: int, request_id=None):
        self.request_id = request_id
        self.employee = employee
        self.days = days
        self.state = PendingState()
        self._observers = []

    def attach(self, observer: Observer):
        self._observers.append(observer)

    def detach(self, observer: Observer):
        self._observers.remove(observer)

    def notify(self, event: str):
        for observer in self._observers:
            observer.update(self, event)

    def approve(self):
        self.state.approve(self)
        self.notify("approved")

    def reject(self):
        self.state.reject(self)
        self.notify("rejected")

    def __repr__(self):
        return (f"LeaveRequest(request_id={self.request_id}, employee={self.employee.name}, "
                f"days={self.days}, state={type(self.state).__name__})")